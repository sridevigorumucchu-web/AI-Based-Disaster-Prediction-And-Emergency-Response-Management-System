// Auto-detect browser language or fallback to English
const getBrowserLanguage = () => {
  const stored = localStorage.getItem('aegis-language');
  if (stored) return stored;

  const browserLang = navigator.language ? navigator.language.split('-')[0] : 'en';
  const supported = [
    'en', 'te', 'hi', 'ta', 'kn', 'ml', 'mr', 'bn', 'ur',
    'gu', 'pa', 'or', 'as', 'sa', 'kok', 'mni', 'brx', 'doi',
    'mai', 'sat', 'ne', 'ks', 'sd'
  ];
  return supported.includes(browserLang) ? browserLang : 'en';
};

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: getBrowserLanguage(),
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false // React already escapes values
    },
    react: {
      useSuspense: false // avoids issues with custom server setups
    }
  });

